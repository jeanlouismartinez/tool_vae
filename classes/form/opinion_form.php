namespace tool_vae\form;

defined('MOODLE_INTERNAL') || die();

// Not autoloaded - see withdraw_form.php for the fatal error this line prevents.
require_once($CFG->libdir . '/formslib.php');

/**
 * Writing an opinion on a deposit (T-10, lot 5b). Plain text: the opinion is a statement in words.
 *
 * @package    tool_vae
 * @copyright  2026 Jean-Louis Martinez <jeanlouis@martinez.pro>
 * @license    http://www.gnu.org/copyleft/gpl.html GNU GPL v3 or later
 */
class opinion_form extends \moodleform {
    /**
     * Build the form.
     */
    protected function definition() {
        $mform = $this->_form;

        $mform->addElement('textarea', 'opinion', get_string('opinionlabel', 'tool_vae'), [
            'rows' => 8,
            'cols' => 70,
        ]);
        $mform->setType('opinion', PARAM_TEXT);
        $mform->addRule('opinion', null, 'required', null, 'client');

        $this->add_action_buttons(false, get_string('opinionsubmit', 'tool_vae'));
    }
}
